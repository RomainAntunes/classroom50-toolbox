//! `src/lib/bindings.ts`: the TypeScript side of the IPC surface, generated from the Rust
//! types with specta. It holds every command (name, arguments, what it returns), the types
//! they carry and `Events`, the payload of each event (`events.rs`). `src/lib/api.ts` is
//! typed from it, so a field, argument, command or variant renamed or retyped in Rust fails
//! svelte-check. Only this test compiles specta: the app itself never links it.
//!
//! `bindings_are_current` fails when the committed file is stale; `UPDATE_GOLDEN=1 cargo test
//! bindings` rewrites it.

use std::path::Path;

use specta::Types;
use specta::datatype::{DataType, Field, Fields};
use specta::function::collect_functions;
use specta_typescript::Typescript;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands};

/// specta-serde's names for `#[serde(default)]` on a field and on a struct.
const FIELD_DEFAULT: &str = "serde:field:default";
const CONTAINER_DEFAULT: &str = "serde:container:default";

const HEADER: &str = "// Generated by `cargo test bindings` from the Rust types (src-tauri/src/bindings.rs).\n\
     // Don't edit it: change the Rust side, then run `UPDATE_GOLDEN=1 cargo test bindings`.";

fn builder() -> Builder<tauri::Wry> {
    let mut types = Types::default();
    ipc_commands!(collect_functions)(&mut types);
    types.register_mut::<crate::events::Events>();
    let mut dropped = 0;
    types.iter_mut(|ndt| {
        if let Some(ty) = &mut ndt.ty {
            dropped += always_written(ty);
        }
    });
    // Settings has `#[serde(default)]`: none found means specta-serde renamed its keys.
    assert!(dropped > 0, "no `serde:*:default` attribute found to drop");
    Builder::<tauri::Wry>::new()
        // First, so the commands find their types here and keep this version of them.
        .types(&types)
        .commands(ipc_commands!(collect_commands))
        // api.ts throws the Rust `Error`, as plain `invoke` does.
        .error_handling(ErrorHandlingMode::Throw)
        // JSON numbers, as today: no count or size here comes near 2^53.
        .dangerously_cast_bigints_to_number()
}

/// Drops `#[serde(default)]`, which only matters when Rust reads: Rust always writes those
/// fields, so the UI gets them required (`at: string | null`, not `at?: string | null`),
/// and sends whole objects back. `skip_serializing_if` still makes a field optional.
fn always_written(ty: &mut DataType) -> usize {
    fn fields(fields: &mut Fields) -> usize {
        let mut dropped = 0;
        let list: Vec<&mut Field> = match fields {
            Fields::Unit => Vec::new(),
            Fields::Unnamed(unnamed) => unnamed.fields.iter_mut().collect(),
            Fields::Named(named) => named.fields.iter_mut().map(|(_, field)| field).collect(),
        };
        for field in list {
            dropped += usize::from(field.attributes.remove(FIELD_DEFAULT));
            if let Some(ty) = &mut field.ty {
                dropped += always_written(ty);
            }
        }
        dropped
    }
    match ty {
        DataType::Struct(s) => {
            usize::from(s.attributes.remove(CONTAINER_DEFAULT)) + fields(&mut s.fields)
        }
        DataType::Enum(e) => e
            .variants
            .iter_mut()
            .map(|(_, variant)| fields(&mut variant.fields))
            .sum(),
        DataType::Nullable(inner) => always_written(inner),
        DataType::Intersection(parts) => parts.iter_mut().map(always_written).sum(),
        _ => 0,
    }
}

fn render() -> String {
    let dir = std::env::temp_dir().join(format!("c50-bindings-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("bindings.ts");
    builder()
        .export(Typescript::default().header(HEADER), &path)
        .expect("exporting the TypeScript bindings");
    let text = std::fs::read_to_string(&path).unwrap();
    let _ = std::fs::remove_dir_all(&dir);
    text
}

#[test]
fn bindings_are_current() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/bindings.ts");
    let fresh = render();
    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        std::fs::write(&path, &fresh).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == fresh,
        "src/lib/bindings.ts is stale: run `UPDATE_GOLDEN=1 cargo test bindings` in src-tauri"
    );
}
